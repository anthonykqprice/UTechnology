#!/usr/bin/env python3
"""Generate the pack's KubeJS scripts, the addon's data pack JSON and test data from design/.

Reads:  design/slice1-mechanical.yaml, design/multiblocks.yaml, design/ids.yaml
Writes (all marked "generated, do not edit"):
  pack/kubejs/server_scripts/generated/recipes.js      changed, new and build recipes; removals
  pack/kubejs/client_scripts/generated/hide.js         hides the disabled stock multiblocks in JEI
  pack/kubejs/data/utechnology/upgrade_frames/*.json   frames (addon reads these)
  pack/kubejs/data/utechnology/upgrade_modules/*.json  modules
  pack/kubejs/data/utechnology/upgrade_multiblocks/*.json  the four multiblocks
  addon/src/test/resources/bonus_cases.json            bonus math cases from the simulator core
  addon/src/main/resources/data/utechnology/gametest/expectations.json
                                                        IDs, stock recipes and our recipes for GameTests
Run from anywhere: python3 tools/generate.py
"""
import json
import pathlib
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import design  # noqa: E402

HEADER = "Generated by tools/generate.py from design/. Do not edit; change the design files and regenerate."


CHECK = "--check" in sys.argv   # also report (and exit 1) when a file had to change
STALE = []


def write(path, text):
    path = ROOT / path
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        STALE.append(str(path.relative_to(ROOT)))
        print("wrote", path.relative_to(ROOT))


def write_json(path, obj):
    write(path, json.dumps(obj, indent=1, sort_keys=False) + "\n")


def clean_dir(path, keep):
    """Remove generated files that the design no longer produces."""
    d = ROOT / path
    if not d.exists():
        return
    for f in d.iterdir():
        if f.is_file() and f.name not in keep:
            f.unlink()
            STALE.append(str(f.relative_to(ROOT)))
            print("removed", f.relative_to(ROOT))


# ---------------------------------------------------------------- KubeJS recipes

def js_str(s):
    return json.dumps(s)


def recipe_js(d, r):
    """One GTM KubeJS recipe builder call."""
    rtype = d.recipe_type(r["machine"])
    ns, path = rtype.split(":")
    lines = [f"  add(() => event.recipes.{ns}.{path}({js_str(d.builder_id(r))})"]
    items = [d.item_ingredient(k, q) for k, q in r.get("in", {}).items()]
    if items:
        lines.append("    .itemInputs(" + ", ".join(js_str(i) for i in items) + ")")
    for k, q in r.get("fluid_in", {}).items():
        lines.append(f"    .inputFluids(Fluid.of({js_str(d.fluid_id(k))}, {q}))")
    if r.get("circuit") is not None:
        lines.append(f"    .circuit({r['circuit']})")
    outs = [d.item_ingredient(k, q) for k, q in r["out"].items()]
    lines.append("    .itemOutputs(" + ", ".join(js_str(o) for o in outs) + ")")
    lines.append(f"    .duration({d.ticks(r['duration'])}).EUt({r['eut']}), {js_str(d.recipe_id(r))})")
    return "\n".join(lines)


def recipes_js(d):
    out = [f"// {HEADER}", "// Recipes for the mechanical slice and the upgradeable multiblocks.", "",
           "ServerEvents.recipes(event => {",
           "  // Each recipe is added on its own so one bad recipe logs an error instead of stopping the rest.",
           "  const add = (build, id) => { try { build() } catch (e) { console.error(`utechnology: recipe ${id} failed: ${e}`) } }",
           ""]
    out.append("  // Stock recipes replaced by changed recipes (machine and hand-crafting versions)")
    for rid in d.removed_recipe_ids():
        out.append(f"  event.remove({{ id: {js_str(rid)} }})")
    out.append("")
    out.append("  // Disabled stock multiblocks (decision disable-overlapping-large-multiblocks)")
    for mid in d.ids["disabled_multiblocks"]:
        out.append(f"  event.remove({{ output: {js_str(mid)} }})")
    out.append("")
    for title, recs in (("Changed recipes", d.recipes_with_status("changed")),
                        ("New recipes", d.recipes_with_status("new")),
                        ("Builds: machines, cores, controllers, retrofit kits, modules", d.build_recipes())):
        out.append(f"  // {title}")
        for r in recs:
            out.append(recipe_js(d, r))
        out.append("")
    out.append("})")
    return "\n".join(out) + "\n"


def hide_js(d):
    lines = [f"// {HEADER}", "// Disabled stock multiblocks are hidden from JEI.", "",
             "JEIEvents.hideItems(event => {"]
    for mid in d.ids["disabled_multiblocks"]:
        lines.append(f"  event.hide({js_str(mid)})")
    lines.append("})")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- data pack JSON for the addon

def frames_json(d):
    out = {}
    for key, f in d.framework["frames"].items():
        out[key] = {
            "_comment": HEADER,
            "tier": f["tier"],
            "casing": f["casing"],
            "frame_box": f["frame_box"],
            "max_voltage": f["max_voltage"],
            "segment_cap": f["segment_cap"],
            "module_slots": f["module_slots"],
            "retrofit_kit": d.item_id("retrofit_kit_" + key),
        }
    return out


def modules_json(d):
    out = {}
    for key, m in d.framework["module_definitions"].items():
        lock = key == "specialization_lock"
        out[key] = {
            "_comment": HEADER,
            "item": d.item_id("module_" + key),
            "name": key.replace("_", " ").title(),
            "effect": m["effect"],
            "unlocked_at": m["unlocked_at"],
            # the lock runs only one recipe; lock_duration applies to that recipe only
            "lock": lock,
            "lock_duration": m.get("duration", 1.0) if lock else 1.0,
            "duration": 1.0 if lock else m.get("duration", 1.0),
            "energy": m.get("energy", 1.0),
            "parallels": m.get("parallels", 1.0),
            # fluid consumed per parallel (decision batch-bus-upkeep)
            "upkeep_per_parallel": [{"fluid": d.fluid_id(k), "amount": v} for k, v in (m.get("upkeep") or {}).items()],
        }
    return out


def multiblocks_json(d):
    out = {}
    fw = d.framework
    lim = fw["hatches"]["limits"]
    for key, m in d.mb["machines"].items():
        sm = d.slice["machines"][key]
        out[key] = {
            "_comment": HEADER,
            "name": m["name"],
            "controller": d.item_id("controller_" + key),
            "core": d.item_id(m["core"]["id"]),
            "recipe_type": d.recipe_type(sm["runs"][0]),
            "filter": sm.get("filter", "none"),
            "component_items": sorted(d.item_id(k) for k, it in d.slice["items"].items() if it.get("kind") == "component"),
            "max_segments_built": fw["structure"]["max_segments_built"],
            "hatch_limits": {k: {"min": v["min"], "max": v["max"]} for k, v in lim.items()},
            "casings_per_kit": fw["retrofit"]["casings_per_kit"],
        }
    return out


# ---------------------------------------------------------------- GameTest expectations

def expectations(d, recipe_cases):
    stock = []
    for r in d.slice["recipes"]:
        if r["status"] == "stock":
            stock.append(d.recipe_expectation(r))
    for r in d.stock_casing_recipes():
        stock.append(d.recipe_expectation(r))
    ours = [dict(d.recipe_expectation(r), id=d.recipe_id(r))
            for r in d.recipes_with_status("changed") + d.recipes_with_status("new") + d.build_recipes()]
    return {
        "_comment": HEADER,
        "ids": sorted(set(d.all_game_ids()) | set(d.ids["disabled_multiblocks"])),
        # items our changed recipes make: no other recipe may make them (catches a wrong removal ID)
        "replaced_outputs": {d.item_id(k): d.recipe_id(r) for r in d.recipes_with_status("changed") for k in r["out"]},
        "removed_recipes": d.removed_recipe_ids(),
        "disabled_multiblocks": d.ids["disabled_multiblocks"],
        "stock_recipes": stock,
        "our_recipes": ours,
        # simulator results for whole recipes in a 3-segment machine (tools/sim-cases.js), checked in game
        "recipe_cases": recipe_cases,
        # each multiblock's recipe type, core and filter, as the addon registers them
        "multiblocks": {k: {"recipe_type": d.recipe_type(d.slice["machines"][k]["runs"][0]),
                            "core": d.item_id(m["core"]["id"]), "controller": d.item_id("controller_" + k)}
                        for k, m in d.mb["machines"].items()},
    }


# ---------------------------------------------------------------- main

def main():
    d = design.load()
    write("pack/kubejs/server_scripts/generated/recipes.js", recipes_js(d))
    write("pack/kubejs/client_scripts/generated/hide.js", hide_js(d))
    clean_dir("pack/kubejs/server_scripts/generated", {"recipes.js"})
    clean_dir("pack/kubejs/client_scripts/generated", {"hide.js"})
    for sub, objs in (("upgrade_frames", frames_json(d)), ("upgrade_modules", modules_json(d)),
                      ("upgrade_multiblocks", multiblocks_json(d))):
        base = f"pack/kubejs/data/utechnology/{sub}"
        for k, v in objs.items():
            write_json(f"{base}/{k}.json", v)
        clean_dir(base, {f"{k}.json" for k in objs})
    cases = subprocess.run(["node", str(ROOT / "tools/sim-cases.js"), json.dumps(d.ids["items"])],
                           check=True, capture_output=True, text=True).stdout
    write("addon/src/test/resources/bonus_cases.json", cases + "\n")
    write_json("addon/src/main/resources/data/utechnology/gametest/expectations.json",
               expectations(d, json.loads(cases)["recipe_cases"]))
    if CHECK and STALE:
        print("stale generated files (now regenerated; commit them):", ", ".join(STALE))
        sys.exit(1)


if __name__ == "__main__":
    main()
